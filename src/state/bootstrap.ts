import fs from "node:fs/promises";
import path from "node:path";

import { resolveRuntimePaths } from "./paths.js";
import type { NexusConfig } from "./config.js";

const PY_FUNCTIONS_HELPER = `# Auto-generated by Nexus.
# This module lets Python scripts call Nexus tools via the \`nexus tool\` CLI.
#
# Example:
#   from functions import query_data
#   print(query_data("BTC"))
#
# Note: Tool outputs are typically JSON or strings. Errors start with "ERROR:".

from __future__ import annotations

import json
import os
import shutil
import subprocess
from typing import Any, Dict


def _resolve_nexus_command() -> tuple[list[str], str | None]:
    code_dir = (os.environ.get("NEXUS_CODE_DIR") or "").strip()
    if code_dir:
        dist_cli = os.path.join(code_dir, "dist", "index.js")
        if os.path.isfile(dist_cli):
            return ["node", dist_cli], None

    if shutil.which("nexus"):
        return ["nexus"], None

    # Slow fallback for source checkouts without an installed CLI.
    if code_dir and os.path.isfile(os.path.join(code_dir, "package.json")):
        return ["npm", "run", "-s", "dev", "--"], code_dir

    return ["nexus"], None


def _call_tool(name: str, args: Dict[str, Any]) -> str:
    payload = json.dumps(args, ensure_ascii=False)
    command, cwd = _resolve_nexus_command()
    proc = subprocess.run(
        [*command, "tool", name, payload],
        check=False,
        capture_output=True,
        text=True,
        env=os.environ,
        cwd=cwd,
    )
    out = (proc.stdout or "").strip()
    err = (proc.stderr or "").strip()
    if proc.returncode != 0:
        details = "\\n".join(
            [s for s in [f"code={proc.returncode}", f"STDERR:\\n{err}" if err else "", f"STDOUT:\\n{out}" if out else ""] if s]
        )
        return f"ERROR: {' '.join(command)} tool {name} failed ({details})"
    return out


def tool(name: str, **kwargs: Any) -> str:
    return _call_tool(name, kwargs)


def query_data(instrument: str, currency: str = "usd") -> Any:
    out = _call_tool("query_data", {"instrument": instrument, "currency": currency})
    if out.startswith("ERROR:"):
        return out
    try:
        data = json.loads(out)
        return data.get("price", data)
    except Exception:
        return out
`;

export async function bootstrapState(config: NexusConfig): Promise<void> {
  const paths = await resolveRuntimePaths(config);
  await fs.mkdir(paths.stateDir, { recursive: true });
  await fs.mkdir(paths.workspaceDir, { recursive: true });

  // Seed Python helper so scripts can call Nexus tools via `nexus tool`.
  try {
    const helpersPath = path.join(paths.workspaceDir, "functions.py");
    await fs.stat(helpersPath);
  } catch {
    try {
      await fs.writeFile(path.join(paths.workspaceDir, "functions.py"), PY_FUNCTIONS_HELPER, "utf8");
    } catch {
      // ignore
    }
  }

}
