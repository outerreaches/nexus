export async function bootstrapState(config: NexusConfig): Promise<{ stateDir: string; workspaceDir: string }> {
  const paths = await resolveRuntimePaths(config);
  await fs.mkdir(paths.stateDir, { recursive: true });
  await fs.mkdir(paths.workspaceDir, { recursive: true });

  // Seed minimal Python helpers (so scripts can call Nexus tools via `nexus tool`).
  try {
    const helpersPath = path.join(paths.workspaceDir, "functions.py");
    await fs.stat(helpersPath);
  } catch {
    try {
      await fs.writeFile(path.join(paths.workspaceDir, "functions.py"), PY_FUNCTIONS_HELPER, "utf8");
    } catch {
      // ignore
    }
  }

  try {
    const runnerPath = path.join(paths.workspaceDir, "run_python_with_tools.py");
    await fs.stat(runnerPath);
  } catch {
    try {
      await fs.writeFile(path.join(paths.workspaceDir, "run_python_with_tools.py"), PY_RUNNER_HELPER, "utf8");
    } catch {
      // ignore
    }
  }

  // Seed personalization files that don't exist yet (idempotent).
  // SOUL.md, IDENTITY.md, USER.md are created by the onboarding process.
  // AGENTS.md, CODEGUIDE.md, HEARTBEAT.md are seeded here if missing.
  // All personalization files live in stateDir (not workspaceDir).
  const seedFiles: [string, string][] = [
    [AGENTS_FILENAME, getDefaultAgentsTemplate()],
    [CODEGUIDE_FILENAME, getDefaultCodeguideTemplate()],
    [HEARTBEAT_FILENAME, getDefaultHeartbeatTemplate()],
  ];
  for (const [filename, content] of seedFiles) {
    const filePath = path.join(paths.stateDir, filename);
    try {
      await fs.stat(filePath);
    } catch {
      try {
        await fs.writeFile(filePath, content, "utf8");
      } catch {
        // ignore
      }
    }
  }

  return { stateDir: paths.stateDir, workspaceDir: paths.workspaceDir };
}
