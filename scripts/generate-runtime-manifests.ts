import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

export type GenerateRuntimeManifestsResult = {
  changed: string[];
  files: {
    generatedSources: string[];
    generatedRuntimeTools: string[];
  };
};

const MODULE_SOURCE_EXTS = new Set([".ts", ".tsx", ".mts", ".cts"]);

function toPosixPath(value: string): string {
  return value.split(path.sep).join(path.posix.sep);
}

function shouldIncludeModuleFile(fileName: string): boolean {
  const ext = path.extname(fileName);
  if (!MODULE_SOURCE_EXTS.has(ext)) return false;
  if (fileName.endsWith(".d.ts")) return false;
  if (fileName.includes(".test.")) return false;
  if (fileName.includes(".spec.")) return false;
  return true;
}

async function listModuleFiles(rootDir: string): Promise<string[]> {
  try {
    const entries = await fs.readdir(rootDir, { withFileTypes: true });
    const files: string[] = [];
    for (const entry of entries) {
      const fullPath = path.join(rootDir, entry.name);
      if (entry.isDirectory()) {
        files.push(...await listModuleFiles(fullPath));
        continue;
      }
      if (!entry.isFile()) continue;
      if (!shouldIncludeModuleFile(entry.name)) continue;
      files.push(fullPath);
    }
    return files.sort((left, right) => left.localeCompare(right));
  } catch (err) {
    const code = typeof err === "object" && err !== null && "code" in err ? (err as { code?: string }).code : undefined;
    if (code === "ENOENT") return [];
    throw err;
  }
}

function toImportSpecifier(fromFile: string, toFile: string): string {
  const fromDir = path.dirname(fromFile);
  const relative = path.relative(fromDir, toFile);
  const withoutExt = relative.replace(/\.[^.]+$/, "");
  const withJsExt = `${toPosixPath(withoutExt)}.js`;
  if (withJsExt.startsWith(".")) return withJsExt;
  return `./${withJsExt}`;
}

function buildNamespaceImports(params: {
  generatedFile: string;
  moduleFiles: string[];
  namespacePrefix: string;
}): { importLines: string[]; moduleRefs: Array<{ file: string; namespaceName: string }> } {
  const importLines: string[] = [];
  const moduleRefs: Array<{ file: string; namespaceName: string }> = [];
  for (const [index, moduleFile] of params.moduleFiles.entries()) {
    const namespaceName = `${params.namespacePrefix}${index}`;
    importLines.push(`import * as ${namespaceName} from "${toImportSpecifier(params.generatedFile, moduleFile)}";`);
    moduleRefs.push({
      file: toPosixPath(path.relative(path.dirname(params.generatedFile), moduleFile)),
      namespaceName,
    });
  }
  return { importLines, moduleRefs };
}

export function renderGeneratedSourcesModule(params: {
  generatedFile: string;
  moduleFiles: string[];
}): string {
  const { importLines, moduleRefs } = buildNamespaceImports({
    generatedFile: params.generatedFile,
    moduleFiles: params.moduleFiles,
    namespacePrefix: "sourceModule",
  });

  const lines = [
    "// Auto-generated by scripts/generate-runtime-manifests.ts. Do not edit by hand.",
    'import type { DataSource } from "./types.js";',
    "",
    ...importLines,
    "",
    "type GeneratedSourceModule = Record<string, unknown>;",
    "",
    "function isGeneratedDataSource(value: unknown): value is DataSource {",
    '  if (!value || typeof value !== "object") return false;',
    "  const candidate = value as Partial<DataSource>;",
    '  return typeof candidate.id === "string" &&',
    '    typeof candidate.name === "string" &&',
    '    typeof candidate.description === "string" &&',
    "    Array.isArray(candidate.tags) &&",
    '    typeof candidate.schemaVersion === "number" &&',
    '    typeof candidate.defaultTtlMs === "number" &&',
    '    typeof candidate.fetch === "function" &&',
    '    typeof candidate.normalize === "function";',
    "}",
    "",
    "function resolveGeneratedDataSource(moduleExports: GeneratedSourceModule, file: string): DataSource {",
    "  const matches = Object.entries(moduleExports).filter(([, value]) => isGeneratedDataSource(value));",
    "  if (matches.length !== 1) {",
    '    throw new Error(`Expected exactly one DataSource export in ${file}, found ${matches.length}.`);',
    "  }",
    "  return matches[0]![1] as DataSource;",
    "}",
    "",
    "const GENERATED_SOURCE_MODULES: ReadonlyArray<{ file: string; exports: GeneratedSourceModule }> = [",
    ...moduleRefs.map((entry) => `  { file: ${JSON.stringify(entry.file)}, exports: ${entry.namespaceName} },`),
    "];",
    "",
    "export const GENERATED_DATA_SOURCES: readonly DataSource[] = GENERATED_SOURCE_MODULES.map((entry) => {",
    "  return resolveGeneratedDataSource(entry.exports, entry.file);",
    "});",
    "",
    "export const GENERATED_DATA_SOURCE_MANIFEST = GENERATED_DATA_SOURCES.map((source, index) => ({",
    "  file: GENERATED_SOURCE_MODULES[index]!.file,",
    "  sourceId: source.id,",
    "  sourceName: source.name,",
    "}));",
    "",
  ];
  return `${lines.join("\n")}\n`;
}

export function renderGeneratedRuntimeToolsModule(params: {
  generatedFile: string;
  moduleFiles: string[];
}): string {
  const { importLines, moduleRefs } = buildNamespaceImports({
    generatedFile: params.generatedFile,
    moduleFiles: params.moduleFiles,
    namespacePrefix: "runtimeToolModule",
  });

  const lines = [
    "// Auto-generated by scripts/generate-runtime-manifests.ts. Do not edit by hand.",
    'import type { Tool } from "../core/tools.js";',
    "",
    ...importLines,
    "",
    "type GeneratedRuntimeToolModule = Record<string, unknown>;",
    "",
    "function isGeneratedRuntimeTool(value: unknown): value is Tool {",
    '  if (!value || typeof value !== "object") return false;',
    "  const candidate = value as Partial<Tool>;",
    '  return typeof candidate.name === "string" &&',
    '    typeof candidate.description === "string" &&',
    '    typeof candidate.execute === "function" &&',
    '    !!candidate.jsonSchema && typeof candidate.jsonSchema === "object";',
    "}",
    "",
    "function resolveGeneratedRuntimeTool(moduleExports: GeneratedRuntimeToolModule, file: string): Tool {",
    "  const matches = Object.entries(moduleExports).filter(([, value]) => isGeneratedRuntimeTool(value));",
    "  if (matches.length !== 1) {",
    '    throw new Error(`Expected exactly one Tool export in ${file}, found ${matches.length}.`);',
    "  }",
    "  return matches[0]![1] as Tool;",
    "}",
    "",
    "const GENERATED_RUNTIME_TOOL_MODULES: ReadonlyArray<{ file: string; exports: GeneratedRuntimeToolModule }> = [",
    ...moduleRefs.map((entry) => `  { file: ${JSON.stringify(entry.file)}, exports: ${entry.namespaceName} },`),
    "];",
    "",
    "export const GENERATED_RUNTIME_TOOLS: readonly Tool[] = GENERATED_RUNTIME_TOOL_MODULES.map((entry) => {",
    "  return resolveGeneratedRuntimeTool(entry.exports, entry.file);",
    "});",
    "",
    "export const GENERATED_RUNTIME_TOOL_MANIFEST = GENERATED_RUNTIME_TOOLS.map((tool, index) => ({",
    "  file: GENERATED_RUNTIME_TOOL_MODULES[index]!.file,",
    "  toolName: tool.name,",
    "}));",
    "",
  ];
  return `${lines.join("\n")}\n`;
}

async function writeIfChanged(filePath: string, nextContent: string): Promise<boolean> {
  let currentContent = "";
  try {
    currentContent = await fs.readFile(filePath, "utf8");
  } catch (err) {
    const code = typeof err === "object" && err !== null && "code" in err ? (err as { code?: string }).code : undefined;
    if (code !== "ENOENT") throw err;
  }
  if (currentContent === nextContent) return false;
  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, nextContent, "utf8");
  return true;
}

export async function generateRuntimeManifests(repoRoot: string): Promise<GenerateRuntimeManifestsResult> {
  const root = path.resolve(repoRoot);
  const intakeSourcesRoot = path.join(root, "src", "data-intake", "sources");
  const runtimeToolsRoot = path.join(root, "src", "tools", "runtime");
  const generatedSourcesFile = path.join(root, "src", "data-intake", "generated-sources.ts");
  const generatedRuntimeToolsFile = path.join(root, "src", "tools", "generated-runtime-tools.ts");

  await fs.mkdir(runtimeToolsRoot, { recursive: true });

  const intakeModuleFiles = (await listModuleFiles(intakeSourcesRoot)).filter((filePath) => {
    return path.basename(filePath) !== "index.ts";
  });
  const runtimeToolModuleFiles = await listModuleFiles(runtimeToolsRoot);

  const changed: string[] = [];
  if (await writeIfChanged(generatedSourcesFile, renderGeneratedSourcesModule({
    generatedFile: generatedSourcesFile,
    moduleFiles: intakeModuleFiles,
  }))) {
    changed.push(toPosixPath(path.relative(root, generatedSourcesFile)));
  }
  if (await writeIfChanged(generatedRuntimeToolsFile, renderGeneratedRuntimeToolsModule({
    generatedFile: generatedRuntimeToolsFile,
    moduleFiles: runtimeToolModuleFiles,
  }))) {
    changed.push(toPosixPath(path.relative(root, generatedRuntimeToolsFile)));
  }

  return {
    changed,
    files: {
      generatedSources: intakeModuleFiles.map((filePath) => toPosixPath(path.relative(root, filePath))),
      generatedRuntimeTools: runtimeToolModuleFiles.map((filePath) => toPosixPath(path.relative(root, filePath))),
    },
  };
}

async function main(): Promise<void> {
  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const result = await generateRuntimeManifests(repoRoot);
  const changedSummary = result.changed.length > 0 ? result.changed.join(", ") : "(none)";
  process.stdout.write(
    `generated manifests changed=${changedSummary} ` +
    `sources=${result.files.generatedSources.length} runtime_tools=${result.files.generatedRuntimeTools.length}\n`,
  );
}

const entryPath = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (entryPath === fileURLToPath(import.meta.url)) {
  await main();
}
